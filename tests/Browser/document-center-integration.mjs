import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createHmac } from 'node:crypto';
import { chromium } from 'playwright';
const origin = 'http://127.0.0.1:8136';
const output = process.env.AJ136_BROWSER_OUTPUT ?? '.local/aj136/browser';
const fixturePath = process.env.AJ136_FIXTURE ?? '.local/aj136/fixture.json';
const fixture = JSON.parse(await readFile(fixturePath, 'utf8'));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const results = [];
const errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await context.newPage();
page.setDefaultTimeout(15000);
page.on('pageerror', error => errors.push(error.message));
function totp(secretValue) {
    const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
    const bits = [...secretValue].map(c => {
        const value = alphabet.indexOf(c);
        if (value < 0) throw new Error('Synthetic MFA fixture secret is invalid.');
        return value.toString(2).padStart(5, '0');
    }).join('');
    const secret = Buffer.from(bits.match(/.{8}/g).map(b => parseInt(b, 2)));
    const counter = Buffer.alloc(8); counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000)));
    const digest = createHmac('sha1', secret).update(counter).digest();
    return String((digest.readUInt32BE(digest[19] & 15) & 0x7fffffff) % 1000000).padStart(6, '0');
}
try {
    await page.goto(origin + '/login');
    await page.locator('input[type=email]').fill(fixture.email);
    await page.locator('input[type=password]').fill(fixture.password);
    await page.getByRole('button', { name: /^Sign in$/i }).click();
    await page.getByLabel('Authenticator code', { exact: true }).fill(totp(fixture.mfa_secret));
    await page.getByRole('button', { name: 'Verify and continue' }).click();
    await page.waitForURL(url => !url.pathname.includes('/security/mfa'));
    results.push('real password + TOTP login');
    await page.goto(origin + '/documents?mode=records');
    await page.getByRole('heading', { name: 'Document Center', exact: true }).waitFor();
    assert.equal(await page.locator('.dc-record').count(), 25);
    await page.getByRole('button', { name: 'Next', exact: true }).click();
    await page.waitForURL(/page=2/);
    assert.equal(await page.locator('.dc-record').count(), 2);
    await page.getByRole('button', { name: 'Previous', exact: true }).click();
    await page.waitForURL(/page=1/);
    await page.getByLabel('Record sort order').selectOption('oldest');
    await page.getByLabel('Record search and filters').getByRole('button', { name: 'Search', exact: true }).click();
    await page.waitForURL(/sort=oldest/);
    assert.match(await page.locator('.dc-record').first().innerText(), /record 00/);
    await page.getByRole('button', { name: 'Inspect metadata for AJ136 Synthetic record 00', exact: true }).click();
    await page.screenshot({ path: output + '/records-desktop.png', fullPage: true });
    results.push('27 real records: server pagination, sorting, metadata');
    await page.getByLabel('Search authorized records').fill('NO-SUCH-SYNTHETIC-RECORD');
    await page.getByLabel('Record search and filters').getByRole('button', { name: 'Search', exact: true }).click();
    await page.getByText('No authorized records match these filters. Try adjusting your search or filters.').waitFor();
    results.push('empty search');
    await page.getByRole('link', { name: 'Files', exact: true }).click();
    await page.waitForURL(/mode=files/);
    await page.getByRole('heading', { name: 'Document Center', exact: true }).waitFor();
    await page.goto(origin + '/documents?mode=files&document=' + fixture.download);
    await page.getByRole('link', { name: 'Download file', exact: true }).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Download file', exact: true }).click();
    const download = await downloadPromise;
    assert.equal(await download.failure(), null);
    await download.saveAs(output + '/synthetic-download.pdf');
    assert.match(await readFile(output + '/synthetic-download.pdf', 'utf8'), /AJ136 synthetic file 0/);
    results.push('selected file metadata + protected download bytes');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: output + '/files-mobile.png', fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile horizontal overflow');
    await page.getByLabel('File sort order').selectOption('oldest');
    await page.getByRole('button', { name: /^Apply/ }).click();
    await page.waitForURL(/sort=oldest/);
    results.push('mobile files, server sort and no horizontal overflow');
    await page.route('**/documents?**', route => route.abort('failed'));
    await page.getByRole('button', { name: /^Apply/ }).click();
    await page.getByRole('alert').filter({ hasText: 'Connection interrupted' }).waitFor();
    await page.unroute('**/documents?**');
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Connection interrupted' }).waitFor({ state: 'hidden' });
    results.push('network failure surfaced and retry recovered');
    assert.deepEqual(errors, []);
} catch (error) {
    await page.screenshot({ path: output + '/failure.png', fullPage: true });
    await writeFile(output + '/failure.txt', await page.locator('body').innerText());
    throw error;
} finally {
    await writeFile(output + '/results.json', JSON.stringify({ results, errors }, null, 2));
    await browser.close();
}
