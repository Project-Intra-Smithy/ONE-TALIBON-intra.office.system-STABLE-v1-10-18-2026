-- Execute after G1B_DISPOSABLE_PG16_ROLE_INSTALL_R1.sql as the disposable bootstrap superuser.
\set ON_ERROR_STOP on
BEGIN;
SET LOCAL statement_timeout = '30s';

DO $catalog$
DECLARE bad integer;
BEGIN
  SELECT count(*) INTO bad FROM pg_roles WHERE rolname IN
    ('kirion_g1b_owner','kirion_g1b_migrator','kirion_g1b_app','kirion_g1b_custody','kirion_g1b_repair')
    AND (rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication OR rolbypassrls OR rolinherit);
  IF bad <> 0 THEN RAISE EXCEPTION 'unsafe role attributes: %', bad; END IF;
  IF NOT pg_has_role('kirion_g1b_migrator','kirion_g1b_owner','MEMBER')
     OR pg_has_role('kirion_g1b_app','kirion_g1b_owner','MEMBER')
     OR pg_has_role('kirion_g1b_custody','kirion_g1b_owner','MEMBER') THEN
    RAISE EXCEPTION 'unexpected owner membership lattice';
  END IF;
  SELECT count(*) INTO bad FROM pg_tables t JOIN pg_class c
    ON c.relname=t.tablename AND c.relnamespace='public'::regnamespace
    WHERE t.schemaname='public' AND c.relowner <> 'kirion_g1b_owner'::regrole;
  IF bad <> 0 THEN RAISE EXCEPTION 'application tables outside owner boundary: %', bad; END IF;
  SELECT count(*) INTO bad FROM pg_proc p WHERE p.pronamespace='public'::regnamespace
    AND p.proname LIKE 'kirion_plan_%' AND
      (p.proowner <> 'kirion_g1b_owner'::regrole OR p.prosecdef
       OR has_function_privilege('kirion_g1b_app',p.oid,'EXECUTE')
       OR has_function_privilege('kirion_g1b_custody',p.oid,'EXECUTE'));
  IF bad <> 0 THEN RAISE EXCEPTION 'unsafe Plan function owner/ACL/security mode: %', bad; END IF;
END $catalog$;

-- A NOINHERIT migration login cannot perform DDL until it explicitly assumes owner.
SET LOCAL ROLE kirion_g1b_migrator;
DO $migrator_denied$ BEGIN
  BEGIN EXECUTE 'CREATE TABLE public.g1b_should_not_exist(id integer)';
    RAISE EXCEPTION 'migration DDL unexpectedly inherited owner';
  EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'PASS migration DDL without SET ROLE denied SQLSTATE %', SQLSTATE;
  END;
END $migrator_denied$;
SET LOCAL ROLE kirion_g1b_owner;
CREATE TABLE public.g1b_owner_probe(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
ALTER TABLE public.users ADD COLUMN g1b_migration_probe boolean;
ALTER TABLE public.users DROP COLUMN g1b_migration_probe;
CREATE FUNCTION public.g1b_owner_default_acl_probe() RETURNS integer LANGUAGE sql AS 'SELECT 1';
DO $owner_check$ BEGIN
  IF (SELECT relowner FROM pg_class WHERE oid='public.g1b_owner_probe'::regclass) <> 'kirion_g1b_owner'::regrole
     OR EXISTS (SELECT 1 FROM pg_proc p
       CROSS JOIN LATERAL aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
       WHERE p.oid='public.g1b_owner_default_acl_probe()'::regprocedure
         AND a.grantee=0 AND a.privilege_type='EXECUTE') THEN
    RAISE EXCEPTION 'owner/default privilege check failed';
  END IF;
END $owner_check$;
RESET ROLE;

-- CREATE OR REPLACE by the owner preserves owner and ACL; nonowners are rejected.
SET LOCAL ROLE kirion_g1b_owner;
DO $replace_same$ BEGIN
  EXECUTE pg_get_functiondef('public.kirion_plan_document_guard()'::regprocedure);
END $replace_same$;
RESET ROLE;
SET LOCAL ROLE kirion_g1b_app;
DO $replace_denied$ BEGIN
  BEGIN EXECUTE 'CREATE OR REPLACE FUNCTION public.kirion_plan_document_guard() RETURNS trigger LANGUAGE plpgsql AS ''BEGIN RETURN NEW; END''';
    RAISE EXCEPTION 'ordinary app replaced protected function';
  EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'PASS unauthorized replacement denied SQLSTATE %', SQLSTATE;
  END;
END $replace_denied$;
RESET ROLE;

-- Synthetic owner fixtures; all data changes roll back.
INSERT INTO public.plan_families(public_id,title,created_at,updated_at)
VALUES ('10000000-0000-4000-8000-000000000001','G1B family',now(),now());
INSERT INTO public.plan_editions(public_id,plan_family_id,edition_label,created_at,updated_at)
SELECT '10000000-0000-4000-8000-000000000002',id,'G1B edition',now(),now()
FROM public.plan_families WHERE public_id='10000000-0000-4000-8000-000000000001';
INSERT INTO public.documents(public_id,title,storage_disk,storage_path,created_at,updated_at)
VALUES ('10000000-0000-4000-8000-000000000003','G1B custody document','local','g1b/synthetic.pdf',now(),now());

SET LOCAL ROLE kirion_g1b_app;
INSERT INTO public.documents(public_id,title,storage_disk,storage_path,created_at,updated_at)
VALUES ('10000000-0000-4000-8000-000000000004','ordinary app document','local','ordinary/test.txt',now(),now());
UPDATE public.documents SET title='ordinary app document updated'
 WHERE public_id='10000000-0000-4000-8000-000000000004';
INSERT INTO public.document_links(document_id,linkable_type,linkable_id,relationship,created_at,updated_at)
SELECT id,'App\\Models\\Transaction',999999,'attachment',now(),now() FROM public.documents
 WHERE public_id='10000000-0000-4000-8000-000000000004';
DELETE FROM public.document_links WHERE document_id=(SELECT id FROM public.documents WHERE public_id='10000000-0000-4000-8000-000000000004');
DELETE FROM public.documents WHERE public_id='10000000-0000-4000-8000-000000000004';
DO $app_denials$ BEGIN
  BEGIN UPDATE public.documents SET security_domain='EVER_PLAN' WHERE public_id='10000000-0000-4000-8000-000000000003';
    RAISE EXCEPTION 'app changed provenance'; EXCEPTION WHEN insufficient_privilege THEN RAISE NOTICE 'PASS app provenance denied SQLSTATE %',SQLSTATE; END;
  BEGIN DELETE FROM public.plan_document_origin_receipts WHERE false;
    RAISE EXCEPTION 'app deleted receipt'; EXCEPTION WHEN insufficient_privilege THEN RAISE NOTICE 'PASS app receipt delete denied SQLSTATE %',SQLSTATE; END;
  BEGIN CREATE TABLE public.g1b_app_ddl(id integer);
    RAISE EXCEPTION 'app created schema object'; EXCEPTION WHEN insufficient_privilege THEN RAISE NOTICE 'PASS app DDL denied SQLSTATE %',SQLSTATE; END;
  BEGIN INSERT INTO public.document_links(document_id,linkable_type,linkable_id,relationship,created_at,updated_at)
    SELECT id,'App\\Models\\PlanEdition',1,'attachment',now(),now() FROM public.documents WHERE public_id='10000000-0000-4000-8000-000000000003';
    RAISE EXCEPTION 'generic Plan link accepted'; EXCEPTION WHEN check_violation THEN RAISE NOTICE 'PASS generic Plan link denied SQLSTATE %',SQLSTATE; END;
END $app_denials$;
RESET ROLE;

SET LOCAL ROLE kirion_g1b_custody;
UPDATE public.documents SET security_domain='EVER_PLAN' WHERE public_id='10000000-0000-4000-8000-000000000003';
INSERT INTO public.plan_document_bindings(plan_edition_id,document_id,role,revision_no,binding_state,created_at,updated_at)
SELECT e.id,d.id,'master',1,'QUARANTINED',now(),now() FROM public.plan_editions e CROSS JOIN public.documents d
 WHERE e.public_id='10000000-0000-4000-8000-000000000002' AND d.public_id='10000000-0000-4000-8000-000000000003';
DO $custody_denials$ BEGIN
  BEGIN UPDATE public.documents SET storage_path='tampered' WHERE public_id='10000000-0000-4000-8000-000000000003';
    RAISE EXCEPTION 'custody changed storage'; EXCEPTION WHEN insufficient_privilege THEN RAISE NOTICE 'PASS custody storage denied SQLSTATE %',SQLSTATE; END;
  BEGIN UPDATE public.documents SET security_domain='LEGACY_CTW' WHERE public_id='10000000-0000-4000-8000-000000000003';
    RAISE EXCEPTION 'custody downgraded provenance'; EXCEPTION WHEN check_violation THEN RAISE NOTICE 'PASS downgrade denied SQLSTATE %',SQLSTATE; END;
  BEGIN DELETE FROM public.plan_document_bindings WHERE document_id=(SELECT id FROM public.documents WHERE public_id='10000000-0000-4000-8000-000000000003');
    RAISE EXCEPTION 'custody deleted binding'; EXCEPTION WHEN insufficient_privilege THEN RAISE NOTICE 'PASS custody binding delete denied SQLSTATE %',SQLSTATE; END;
END $custody_denials$;
RESET ROLE;

SET LOCAL ROLE kirion_g1b_repair;
DO $repair_denied$ BEGIN
  BEGIN UPDATE public.documents SET security_domain='LEGACY_CTW' WHERE false;
    RAISE EXCEPTION 'repair wrote provenance'; EXCEPTION WHEN insufficient_privilege THEN RAISE NOTICE 'PASS repair denied SQLSTATE %',SQLSTATE; END;
END $repair_denied$;
RESET ROLE;

ROLLBACK;
SELECT 'G1B_DISPOSABLE_ROLE_POLICY_VERIFIED_AND_FIXTURES_ROLLED_BACK' AS result;
